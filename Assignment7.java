public class StringMethods {
    public static void main(String[] args) {

        String name = "Java";

        // 1. length()
        System.out.println("Length: " + name.length());

        // 2. toUpperCase()
        System.out.println("Uppercase: " + name.toUpperCase());

        // 3. charAt()
        System.out.println("First character: " + name.charAt(0));
    }
}
